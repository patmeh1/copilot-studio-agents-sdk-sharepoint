<#
.SYNOPSIS
  Builds the "Copilot Studio Agent (Agents SDK)" SPFx package (.sppkg) with tenant defaults baked in.

.DESCRIPTION
  1. Writes src/config/defaults.ts with the Entra SPA app (client) ID (and optional tenant ID) so page authors
     only have to paste an agent connection string into the web part.
  2. Optionally sets the solution version (must increase for every re-deployment).
  3. Runs npm ci/install (first time), gulp bundle --ship and gulp package-solution --ship using Node 22
     (SPFx 1.21.1 requires Node >= 22.14 < 23; pass -NodePath if Node 22 is not first on PATH).

.EXAMPLE
  .\Build-SpfxPackage.ps1 -AppClientId 1f06ba87-8706-4216-bb08-f8d10c3118cf -Version 1.0.2.0 `
      -NodePath C:\tools\node-v22.23.3-win-x64
#>
[CmdletBinding()]
param(
    [Parameter(Mandatory)] [ValidatePattern('^[0-9a-fA-F-]{36}$')] [string] $AppClientId,
    [string] $TenantId = '',
    [ValidatePattern('^\d+\.\d+\.\d+\.\d+$')] [string] $Version,
    [string] $NodePath,
    [string] $SolutionPath = (Join-Path $PSScriptRoot '..\spfx-copilot-agent')
)

$ErrorActionPreference = 'Stop'
$SolutionPath = (Resolve-Path $SolutionPath).Path
if ($NodePath) { $env:Path = "$NodePath;$env:Path" }

$nodeVersion = (& node -v).TrimStart('v')
if (-not ($nodeVersion -match '^22\.')) { throw "SPFx 1.21.1 needs Node 22.x (found $nodeVersion). Pass -NodePath <folder with node 22>." }

# 1. Tenant defaults
$defaults = @"
/**
 * Tenant-level defaults applied when a page author leaves a web part property empty.
 * Regenerated by scripts/Build-SpfxPackage.ps1 (-AppClientId / -TenantId) before packaging.
 * Client IDs are public identifiers, not secrets.
 */
export const DEFAULT_APP_CLIENT_ID: string = '$AppClientId';

/** Leave empty to use the tenant of the SharePoint site that hosts the web part. */
export const DEFAULT_TENANT_ID: string = '$TenantId';
"@
Set-Content -Path (Join-Path $SolutionPath 'src\config\defaults.ts') -Value $defaults -Encoding utf8

# 2. Version (solution + feature + package.json so the web part manifest version follows)
if ($Version) {
    $psPath = Join-Path $SolutionPath 'config\package-solution.json'
    $ps = Get-Content $psPath -Raw | ConvertFrom-Json
    $ps.solution.version = $Version
    foreach ($f in $ps.solution.features) { $f.version = $Version }
    $ps | ConvertTo-Json -Depth 10 | Set-Content $psPath -Encoding utf8
    $pkgPath = Join-Path $SolutionPath 'package.json'
    $semver = ($Version.Split('.')[0..2]) -join '.'
    (Get-Content $pkgPath -Raw) -replace '"version":\s*"[^"]+"', "`"version`": `"$semver`"" | Set-Content $pkgPath -NoNewline -Encoding utf8
}

# 3. Build
Push-Location $SolutionPath
try {
    if (-not (Test-Path 'node_modules')) {
        if (Test-Path 'package-lock.json') { npm ci --no-audit --no-fund } else { npm install --no-audit --no-fund }
        if ($LASTEXITCODE -ne 0) { throw 'npm install failed' }
    }
    npx gulp clean | Out-Null
    npx gulp bundle --ship
    if ($LASTEXITCODE -ne 0) { throw 'gulp bundle --ship failed' }
    npx gulp package-solution --ship
    if ($LASTEXITCODE -ne 0) { throw 'gulp package-solution --ship failed' }
    $pkg = Get-ChildItem 'sharepoint\solution\*.sppkg' | Select-Object -First 1
    Write-Host "Package ready: $($pkg.FullName)" -ForegroundColor Green
}
finally {
    Pop-Location
}
